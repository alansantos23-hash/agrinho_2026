let contador = 0;
const elementoTela = document.getElementById('valor-contador');
const botaoMais = document.getElementById('btn-incrementar');

// Substitui o "if digitalRead == LOW"
botaoMais.addEventListener('click', () => {
  contador++;
  elementoTela.textContent = contador; // Atualiza o display
});




















































































































